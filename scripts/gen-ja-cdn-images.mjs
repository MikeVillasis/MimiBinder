// Regenerates src/lib/tcgdex/ja-cdn-images.ts: Japanese cards whose image exists on TCGdex's CDN although the
// TCGdex API doesn't list it (tcgdex/cards-database#2477). Run by hand now and then:
//   node scripts/gen-ja-cdn-images.mjs
// Needs network access to api.tcgdex.net and assets.tcgdex.net. Takes a few minutes (~10k HEAD requests).
import { writeFileSync } from "node:fs";

const API = "https://api.tcgdex.net/v2/ja";
const CDN = "https://assets.tcgdex.net/ja";
// Known bad: from M1S-057 on, the CDN image shows a different card (tcgdex/cards-database#2395).
const EXCLUDE = (setId, localId) => setId === "M1S" && Number.parseInt(localId, 10) >= 57;

async function json(url, tries = 3) {
  for (let i = 0; ; i++) {
    try {
      const r = await fetch(url);
      if (!r.ok) throw new Error(`${r.status} ${url}`);
      return await r.json();
    } catch (e) {
      if (i >= tries - 1) throw e;
      await new Promise((r) => setTimeout(r, 1000));
    }
  }
}
async function exists(url) {
  for (let i = 0; i < 3; i++) {
    try {
      const r = await fetch(url, { method: "HEAD" });
      if (r.status === 404) return false;
      if (r.ok) return true;
    } catch {}
    await new Promise((r) => setTimeout(r, 1000));
  }
  return false;
}
async function pool(items, n, fn) {
  const out = new Array(items.length);
  let next = 0;
  await Promise.all(Array.from({ length: n }, async () => { while (next < items.length) { const i = next++; out[i] = await fn(items[i]); } }));
  return out;
}

const series = await json(`${API}/series`);
const setSerie = new Map();
for (const s of series) for (const set of (await json(`${API}/series/${encodeURIComponent(s.id)}`)).sets ?? []) setSerie.set(set.id, s.id);
const todo = [];
await pool([...setSerie.keys()], 12, async (setId) => {
  const set = await json(`${API}/sets/${encodeURIComponent(setId)}`).catch(() => null);
  for (const c of set?.cards ?? []) if (!c.image && !EXCLUDE(setId, c.localId)) todo.push({ setId, serie: setSerie.get(setId), localId: c.localId });
});
const hits = await pool(todo, 32, (t) => exists(`${CDN}/${t.serie}/${t.setId}/${encodeURIComponent(t.localId)}/low.webp`));
const bySet = {};
todo.forEach((t, i) => { if (hits[i]) (bySet[t.setId] ??= { s: t.serie, ids: [] }).ids.push(t.localId); });

/** "001,002,003,005" -> "001-003,005" for zero-padded numeric runs of the same width. */
function compress(ids) {
  ids.sort((a, b) => (Number.parseInt(a, 10) || 0) - (Number.parseInt(b, 10) || 0) || a.localeCompare(b));
  const out = [];
  for (let i = 0; i < ids.length; ) {
    let j = i;
    while (j + 1 < ids.length && /^\d+$/.test(ids[j + 1]) && /^\d+$/.test(ids[j]) && ids[j + 1].length === ids[j].length && +ids[j + 1] === +ids[j] + 1) j++;
    out.push(j > i ? `${ids[i]}-${ids[j]}` : ids[i]);
    i = j + 1;
  }
  return out.join(",");
}
const entries = Object.keys(bySet).sort().map((k) => `  ${JSON.stringify(k)}: { s: ${JSON.stringify(bySet[k].s)}, ids: ${JSON.stringify(compress(bySet[k].ids))} },`);
const total = Object.values(bySet).reduce((n, v) => n + v.ids.length, 0);
writeFileSync(
  new URL("../src/lib/tcgdex/ja-cdn-images.data.ts", import.meta.url),
  `// GENERATED by scripts/gen-ja-cdn-images.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.\n` +
    `// ${total} Japanese cards whose image is on TCGdex's CDN but missing from the TCGdex API.\n` +
    `// setId -> { s: serie id (CDN path), ids: localIds, runs written "001-115" }.\n` +
    `export const JA_CDN_IMAGES: Record<string, { s: string; ids: string }> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`${total} cards in ${entries.length} sets (checked ${todo.length})`);
